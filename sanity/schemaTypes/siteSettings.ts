import { defineArrayMember, defineField, defineType } from 'sanity';

export const siteSettings = defineType({
	name: 'siteSettings',
	title: 'Site settings',
	type: 'document',
	groups: [
		{ name: 'hero', title: 'Hero' },
		{ name: 'about', title: 'About' },
		{ name: 'contact', title: 'Contact' },
		{ name: 'seo', title: 'Search and sharing' },
	],
	fields: [
		defineField({
			name: 'name',
			title: 'Name',
			description: 'Shown as the big heading at the top of the home page.',
			type: 'string',
			group: 'hero',
			validation: (rule) => rule.required().max(40),
		}),
		defineField({
			name: 'statement',
			title: 'Intro statement',
			description: 'One or two sentences under the name that say what you do.',
			type: 'text',
			rows: 3,
			group: 'hero',
			validation: (rule) => rule.required().max(200),
		}),
		defineField({
			name: 'details',
			title: 'Title block details',
			description:
				'Short facts shown under your name like the title block on an engineering drawing, for example Degree: BEng Automotive. Up to six. Drag to reorder.',
			type: 'array',
			group: 'hero',
			of: [
				defineArrayMember({
					type: 'object',
					name: 'detail',
					fields: [
						defineField({
							name: 'label',
							title: 'Label',
							description: 'For example Degree, Year, Based or Available.',
							type: 'string',
							validation: (rule) => rule.required().max(20),
						}),
						defineField({
							name: 'value',
							title: 'Value',
							description: 'For example BEng Automotive, 3, Coventry or Jul 2027.',
							type: 'string',
							validation: (rule) => rule.required().max(40),
						}),
					],
					preview: { select: { title: 'label', subtitle: 'value' } },
				}),
			],
			validation: (rule) => rule.max(6),
		}),
		defineField({
			name: 'roleLine',
			title: 'Role',
			description: 'For example Automotive engineering student. Leave empty to hide it.',
			type: 'string',
			group: 'hero',
			validation: (rule) => rule.max(80),
		}),
		defineField({
			name: 'availabilityLine',
			title: 'Availability',
			description: 'For example Open to placements and graduate roles. Leave empty to hide it.',
			type: 'string',
			group: 'hero',
			validation: (rule) => rule.max(80),
		}),
		defineField({
			name: 'skills',
			title: 'Skills and tools',
			description:
				'Software, methods and tools you use, for example CATIA or MATLAB. Shown in their own section after About. Drag to reorder. Leave empty to hide the section.',
			type: 'array',
			group: 'about',
			of: [defineArrayMember({ type: 'string', validation: (rule) => rule.required().max(40) })],
			validation: (rule) => rule.max(24).unique(),
		}),
		defineField({
			name: 'about',
			title: 'About text',
			description:
				'Shown in the About section. If you leave it empty, the standard text about your degree and placement search is shown.',
			type: 'text',
			rows: 6,
			group: 'about',
			validation: (rule) => rule.max(600),
		}),
		defineField({
			name: 'profileImage',
			title: 'Profile photo',
			description:
				'Shown beside the About text. A portrait photo works best. Drag the focal point onto your face.',
			type: 'image',
			group: 'about',
			options: { hotspot: true },
			fields: [
				defineField({
					name: 'alt',
					title: 'Alt text',
					description: 'Describe the photo for people who cannot see it.',
					type: 'string',
					validation: (rule) => rule.required().max(200),
				}),
			],
		}),
		defineField({
			name: 'email',
			title: 'Email address',
			description: 'Shown at the bottom of every page as a link people can click to write to you.',
			type: 'string',
			group: 'contact',
			validation: (rule) => rule.required().email(),
		}),
		defineField({
			name: 'linkedinUrl',
			title: 'LinkedIn profile',
			description:
				'Shown next to your email address with a LinkedIn icon. Paste the full address of your profile.',
			type: 'url',
			group: 'contact',
			validation: (rule) => rule.uri({ scheme: ['https'] }),
		}),
		defineField({
			name: 'contactHeading',
			title: 'Contact heading',
			description: 'The question or invitation above the email address.',
			type: 'string',
			group: 'contact',
			validation: (rule) => rule.max(80),
		}),
		defineField({
			name: 'siteTitle',
			title: 'Site title',
			description: 'The title of the home page in browser tabs and search results.',
			type: 'string',
			group: 'seo',
			validation: (rule) => rule.max(70),
		}),
		defineField({
			name: 'siteDescription',
			title: 'Site description',
			description: 'The short summary shown under the title in search results.',
			type: 'text',
			rows: 3,
			group: 'seo',
			validation: (rule) => rule.max(160),
		}),
	],
	preview: { prepare: () => ({ title: 'Site settings' }) },
});
